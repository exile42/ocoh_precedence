<div class="bodyheader">2006-08-31</div>
<p>Wimble releases a new feature - search! Many types of searches are already
  effectively implemented via the  listings by Person, by Award, 
  by Local Group, by Known Alias, and so on. This search feature does, however,
  add a Name search that checks both main names and aliases, and also adds a
  Date search.</p>
<p>If there's a new type of search you're interested in, or a report you're interested
  in, let Wimble know. Do be aware that, by Society Electronic Publication Policy,
  I can't make legal names publicly available. Wimble's catching up on a backlog
  from moving to a new place, but I still want to hear your ideas.</p>
