<div class="bodyheader">2013-01-27</div>
<p>New feature!  In the left-hand navigation, you should now see a link to "<a href="http://wimble.outlandsheralds.org/awards_all.php">All Awards and Orders for the Outlands and Baronies</a>".  This new page gives a quick and easy listing of all the Awards and Orders for the Outlands (including for the baronies), ordered by level of award.  The name of each award is a link to a list of the members of the Award or Order.</p>
<p>Many updates!  In the left-hand navigation, you'll see that the "Awards" header is now "Award Information". This is where to find out information about the award itself - charters, badges, what it's given for, and more.  Speaking of information about the awards themselves, those pages will also now tell you what level of precedence the award has.  Also in the left-hand navigation, under the "People of the Outlands" header, what was "By Award" is now "Award Membership Lists", to be clearer about what it's for.  That page also now has multiple ways to find the award you're looking for.  Some of the back-end code has also been updated, our webminister tells us.</p>
