<p>Court reports should be sent
  to the nobility who hosted the court, Wimble, the Kingdom Scribe, the local
  herald or the court herald (whichever one you aren't), and a courtesy copy to White Stag. Wimble  can be reached at <a href="mailto:&#119;i&#109;b&#108;e@out&#108;ands&#104;eralds.org">&#119;i&#109;b&#108;e
  'at' out&#108;ands&#104;eralds 'dot' org</a>, and White Stag at <a href="mailto:whitestag@outlandsheralds.org">whitestag
  'at' outlandsheralds 'dot' org</a>. Other updates and corrections should be sent to the Wimble Herald (please allow time for Wimble to doublecheck).</p>
<p>When sending court reports, updates, or corrections, please include as much of the following as possible:</p>
<ul>
  <li>Name of event and DATE of award (especially important for multi-day events) </li>
  <li>SCA and legal names of the recipient </li>
  <li>Award name </li>
  <li> Home branch of recipient </li>
  <li> If a scroll was given, if it was a promissory or final, and the name of the scribe(s) </li>
  <li> Membership number, if available. (we use this as a cross-reference.)</li>
</ul>
