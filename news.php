<div class="bodyheader">2010-06-21</div>
<p>June 21, 2010: When listing members of a barony, the list now includes any members of a college or canton within that barony.</p>
<p>There's a new option in the Awards section for &quot;<a href="awards_group.php">By Group</a>&quot; - this will list information about awards for the kingdom and each of the baronies in the Outlands, separated by group. There's also an option for each of the Awards sections for &quot;ALL&quot; - that'll give you a list of all the awards of the Kingdom of the Outlands and all of its baronies. (Note, this doesn't include awards for the Principality of the Outlands.)</p>
